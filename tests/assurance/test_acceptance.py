def test_6_ablation_must_re_expand_to_k0_equivalent_semantics():
    """"An ablated primitive re-expands to K0-equivalent semantics before causal effect is
    accepted." """
    from bestsad.bsir import semantic_hash
    from bestsad.causal import ablate
    from bestsad.kernel import Kernel, Program, Term

    primitive = _primitive("prim:double")
    expansion = app("mul", var("a"), const_int(2))
    p = Primitive("prim:double", ("a",), expansion, (INT,), INT)
    kernel = Kernel({p.primitive_id: (p.params, p.expansion)})
    program = Program((("x", INT),), Term("prim:double", (var("x"),)), INT)
    ablated = ablate(program, "prim:double", kernel)
    assert semantic_hash(ablated, kernel) == semantic_hash(program, kernel)

    # The per-primitive claim carries the ablation as evidence with an EMPIRICAL warrant.
    from bestsad.stats import Interval
    from bestsad.causal import PrimitiveEffect

    effect = PrimitiveEffect(
        primitive_id="prim:double", semantic_hash="abc",
        direct_effect=Interval(0.02, 0.0, 0.04), indirect_effect=Interval(0.0, 0.0, 0.0),
        cross_family_reuse=3, shortcut_shaped=False, compression_shaped=False,
        semantic_gain_v2=4.0,
    )
    claims = primitive_effect_claims([effect], roots=_roots(), producer="causal-plane")
    assert len(claims) == 1
    claim, evidence = claims[0]
    kinds = {e.kind for e in evidence}
    assert "paired_ablation" in kinds and "semantic_gain" in kinds


