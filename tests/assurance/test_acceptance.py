def test_9b_the_report_gate_still_refuses_what_it_must():
    """Delegation must not weaken the gate: the refusals still fire, now via the predicate."""
    from bestsad.stats import ClaimRequest, Preregistration, ReportGate, ReportRefused

    prereg = Preregistration(
        experiment_id="X", primary_endpoint="e",
        conditions=({"condition_id": c} for c in "ABCDEFGHI"),
        seeds_per_condition=8, minimum_interesting_effect={"x": 1},
        multiple_comparison_control={"method": "benjamini_hochberg", "level": 0.05,
                                     "family": ["a"]},
        stopping_rule="fixed", declared_outcome_interpretations={"positive": "p"},
        power_analysis={"powered": True},
    )
    prereg.conditions = tuple(prereg.conditions)
    prereg.commit()
    request = ClaimRequest(
        experiment_id="X", claim_kind="capability",
        conditions_run=("A", "D", "F", "H"),   # I missing
        treatment_beats={"F": True, "H": True, "I": True},
        compression_ratio=1.5, capability_delta=0.08,
        fdr_controlled=True, concentration_test_passed=True, powered=True,
    )
    with pytest.raises(ReportRefused, match="missing I"):
        ReportGate(prereg).certify(request)


