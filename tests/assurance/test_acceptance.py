def test_8_a_null_exp001_produces_a_promotable_negative_result_claim():
    """"A null EXP-001 produces a promoted negative-result ClaimObject when the experiment is
    valid." """
    roots = _roots()
    evidence = [
        make_evidence("experiment_manifest", "artifacts", "manifest", Warrant.DIRECT_OBSERVATION, {}),
        make_evidence("report", "docs/experiments", "report", Warrant.EMPIRICAL, {}),
    ]
    claim = negative_result_claim(
        roots=roots, producer="bestsad.experiments.analysis",
        statement="EXP-001-DR does not support the target effect.",
        search_space_constraint="Abstractions mined from solved curriculum programs are bounded "
                                "by what the searcher already solves.",
        preregistration_content_id="prereg:x", evidence=evidence, outcome_class="h0_consistent",
    )
    # A negative result does not require the controls to have been *beaten* — only that the
    # experiment was valid — because the claim being made is about the absence of an effect.
    context = _full_context(claim, roots, satisfied_conditions=(), defeated_conditions=(),
                            gate_actor="policy-gate")
    verdict = evaluate(claim, context)
    assert verdict.promotable, f"negative result should be promotable: {verdict.blockers}"

    ledger = AssuranceLedger()
    for e in evidence:
        ledger.add_evidence(e)
    ledger.add_claim(claim)
    ledger.add_certificate(_certificate(claim.claim_id))
    gate = PolicyGate(actor="policy-gate")
    verdict, decision = gate.decide(claim, context)
    assert decision is not None
    promoted = ledger.apply_decision(decision)
    assert promoted.status is ClaimState.PROMOTED


