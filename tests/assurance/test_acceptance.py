@pytest.mark.parametrize("missing", ["F", "H", "I"])
def test_4_missing_control_blocks_a_capability_claim_however_high_the_accuracy(missing):
    """"Missing F, H or I prevents a confirmatory capability claim even if treatment accuracy
    is high." """
    claim, roots = _capability()
    present = tuple(c for c in ("F", "H", "I") if c != missing)
    verdict = evaluate(
        claim,
        _full_context(claim, roots, satisfied_conditions=present, defeated_conditions=present,
                      gate_actor="policy-gate"),
    )
    assert not verdict.promotable
    assert any(missing in b and "missing" in b for b in verdict.blockers)


def test_4b_a_control_that_matches_the_treatment_also_blocks_the_claim():
    """§8: "missing/failed F blocks representation-capability promotion" — failed counts too."""
    claim, roots = _capability()
    verdict = evaluate(
        claim,
        _full_context(claim, roots, defeated_conditions=("F", "H"), gate_actor="policy-gate"),
    )
    assert not verdict.promotable
    assert any("matched or beat the treatment" in b for b in verdict.blockers)


