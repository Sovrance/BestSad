def test_10_stale_semantic_certificates_fail_closed_for_core_use():
    """"Stale semantic certificates make compiler/runtime CORE use fail closed." """
    from bestsad.assurance.objects import NON_EXECUTABLE_STATES

    roots = _roots()
    primitive = _primitive()
    claim, evidence = semantic_equivalence_claim(
        primitive, roots=roots, producer="extractor", differential_cases=10_000, exhaustive=True
    )
    from dataclasses import replace

    stale = replace(claim, status=ClaimState.STALE)
    assert stale.status in NON_EXECUTABLE_STATES

    verdict = evaluate(stale, _full_context(stale, roots, gate_actor="policy-gate"))
    assert not verdict.promotable
    assert any("STALE" in b for b in verdict.blockers)


def test_10b_a_moved_root_makes_a_claim_fail_closed_even_before_propagation():
    """Defence in depth: the predicate compares recorded source hashes to live ones, so a claim
    whose root moved fails even if nobody has run invalidation yet."""
    claim, roots = _capability()
    moved = dict(roots.values)
    moved[K0_ROOT] = "k0:something-else"
    verdict = evaluate(
        claim, _full_context(claim, roots, current_source_hashes=moved, gate_actor="policy-gate")
    )
    assert not verdict.promotable
    assert any("source/content hashes have moved" in b for b in verdict.blockers)
