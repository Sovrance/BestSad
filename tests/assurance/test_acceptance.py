def test_7_a_compression_only_primitive_cannot_be_promoted_as_capability_evidence():
    """"A compression-only primitive can be useful but cannot be promoted as generalized
    capability evidence." """
    roots = _roots()
    # A claim whose only warrant is heuristic/asserted can never carry a capability promotion.
    claim = make_claim(
        CAPABILITY, "Compression implies capability.", producer="compressor",
        warrant=Warrant.HEURISTIC,
        evidence=[make_evidence("preregistration", "p", "m", Warrant.HEURISTIC, {})],
    )
    verdict = evaluate(claim, _full_context(claim, roots, gate_actor="policy-gate"))
    assert not verdict.promotable
    assert any("never on its own" in b for b in verdict.blockers)
    assert any("not sufficient for claim class" in b for b in verdict.blockers)


