def test_1_evolution_agent_cannot_promote_its_own_primitive_to_core():
    """"A primitive generated by the evolution agent cannot promote itself to CORE." """
    # The lifecycle refuses the step outright for a non-gate actor.
    with pytest.raises(LifecycleViolation, match="promotion gate"):
        advance_lifecycle("EXPERIMENTALLY_SUPPORTED", "CORE_ELIGIBLE", actor_is_gate=False)
    with pytest.raises(LifecycleViolation, match="promotion gate"):
        advance_lifecycle("CORE_ELIGIBLE", "CORE", actor_is_gate=False)
    # ...and permits it for a gate.
    assert advance_lifecycle("CORE_ELIGIBLE", "CORE", actor_is_gate=True) == "CORE"

    # The gate itself refuses to act when it *is* the producer.
    primitive = _primitive()
    roots = _roots()
    claim, _ev = semantic_equivalence_claim(
        primitive, roots=roots, producer="evolution-agent", differential_cases=1000
    )
    gate = PolicyGate(actor="evolution-agent")
    with pytest.raises(SelfPromotionRefused, match="own promotion"):
        gate.decide(claim, PromotionContext())


def test_1b_ledger_refuses_a_producer_written_promoted_state():
    ledger = AssuranceLedger()
    primitive = _primitive()
    roots = _roots()
    claim, evidence = semantic_equivalence_claim(
        primitive, roots=roots, producer="evolution-agent", differential_cases=1000
    )
    for e in evidence:
        ledger.add_evidence(e)
    ledger.add_claim(claim)
    with pytest.raises(LedgerViolation, match="PolicyGate"):
        ledger.record_state(claim.claim_id, ClaimState.PROMOTED, actor="evolution-agent")


