def _primitive(name: str = "prim:sum") -> Primitive:
    body = app("fold", lam((("acc", INT), ("e", INT)), app("add", var("acc"), var("e"))),
               const_int(0), var("xs"))
    return Primitive(name, ("xs",), body, (TList(INT),), INT, origin="utility")


def _roots():
    return current_roots(preregistration_hash="a" * 64, benchmark_manifest_id="bm:test")


def _certificate(claim_id: str, status: str = "PASS", warrant=Warrant.EMPIRICAL):
    return AssuranceCertificate(
        certificate_id=f"cert:{claim_id[-8:]}", claim_id=claim_id,
        verifier="bestsad.assurance", status=status, warrant=warrant,
    )


def _capability(producer="bestsad.experiments.analysis"):
    roots = _roots()
    evidence = [
        make_evidence("preregistration", "docs/preregistrations", "hash", Warrant.FORMAL, {"h": 1}),
        make_evidence("condition_manifest", "conditions", "manifest", Warrant.DIRECT_OBSERVATION, {}),
        make_evidence("compute_ledger", "telemetry", "ledger", Warrant.DIRECT_OBSERVATION, {}),
        make_evidence("causal_attribution", "causal", "ablation", Warrant.EMPIRICAL, {}),
    ]
    claim = capability_claim(
        roots=roots, producer=producer,
        statement="Evolved representation improves verified compositional OOD synthesis",
        treatment_condition="D", comparators=["A", "F", "G", "H", "I"],
        effect_metric="verified_ood_solve_rate_per_compute", effect=0.08, ci=(0.03, 0.13),
        preregistration_content_id="prereg:x", compute_ledger_id="ledger:x",
        causal_attribution_refs=["attr:1"], evidence=evidence,
    )
    return claim, roots


def _full_context(claim, roots, **overrides):
    base = dict(
        certificate=_certificate(claim.claim_id),
        dependency_states={d: "active" for d in claim.dependency_refs},
        active_assumptions={a: roots.values.get(a, "x") for a in claim.assumption_refs},
        current_source_hashes=dict(roots.values),
        satisfied_conditions=("F", "H", "I"),
        defeated_conditions=("F", "H", "I"),
        concentration_pass=True,
        policy_allows=True,
    )
    base.update(overrides)
    return PromotionContext(**base)


