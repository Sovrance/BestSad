def test_5_condition_g_may_beat_the_treatment_and_is_reported_without_special_handling():
    """"Condition G may beat the treatment and the system reports it without special
    handling." """
    claim, roots = _capability()
    # G is a reference class, not one of the required confound controls, so it never appears in
    # the promotion predicate's required set — there is no code path that special-cases it.
    from bestsad.assurance.claims import CLAIM_CLASSES

    assert "G" not in CLAIM_CLASSES[CAPABILITY].required_conditions
    verdict = evaluate(claim, _full_context(claim, roots, gate_actor="policy-gate"))
    assert verdict.promotable, "G beating the treatment must not itself block promotion"
    # And the analysis reports G's margin alongside, which is asserted in tests/experiments.


