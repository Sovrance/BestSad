def test_2_changing_a_semantic_root_stales_every_dependent_claim():
    """"Changing K0 or BSIR semantic-root content ID stales every dependent primitive/genome
    claim." """
    ledger = AssuranceLedger()
    roots = _roots()
    primitive = _primitive()
    claim, evidence = semantic_equivalence_claim(
        primitive, roots=roots, producer="extractor", differential_cases=5000
    )
    for e in evidence:
        ledger.add_evidence(e)
    ledger.add_claim(claim)

    # A genome claim depending on the primitive claim, and a capability claim on the genome.
    genome_claim = make_claim(
        "genome_validity", "Genome G uses only admitted primitives.",
        producer="genome-builder", warrant=Warrant.RIGOROUS_COMPUTATION,
        evidence=[evidence[0]], dependencies=[claim.claim_id], assumptions=[K0_ROOT],
    )
    ledger.add_claim(genome_claim)
    cap, _ = _capability()
    cap = type(cap)(**{**cap.__dict__, "dependency_refs": (genome_claim.claim_id,)}) \
        if hasattr(cap, "__dict__") else cap
    from dataclasses import replace
    cap = replace(cap, dependency_refs=(genome_claim.claim_id,))
    ledger.add_claim(cap)

    events = ledger.invalidate_from(K0_ROOT, reason="K0 semantics changed")
    affected = {e.node_id for e in events}
    assert claim.claim_id in affected
    assert genome_claim.claim_id in affected, "staleness must reach the genome claim"
    assert cap.claim_id in affected, "staleness must reach the capability claim transitively"
    assert all(e.new_state is ClaimState.STALE for e in events)

    # Nothing was deleted: history remains queryable (§1.5).
    assert ledger.claims[claim.claim_id].status is ClaimState.STALE
    assert ledger.history(claim.claim_id), "the claim's history must survive invalidation"


