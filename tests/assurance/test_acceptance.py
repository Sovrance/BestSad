def test_3_evaluator_integrity_failure_invalidates_capability_claims():
    """"A hidden-evaluator integrity failure invalidates affected capability claims." """
    ledger = AssuranceLedger()
    cap, roots = _capability()
    ledger.add_claim(cap)
    events = ledger.invalidate_from(
        EVALUATOR_ROOT, reason="hidden-test leak detected", quarantine=True
    )
    assert cap.claim_id in {e.node_id for e in events}
    assert ledger.claims[cap.claim_id].status is ClaimState.QUARANTINED
    # Quarantine, not staleness: an integrity breach is not merely out of date.
    assert all(e.new_state is ClaimState.QUARANTINED for e in events)


